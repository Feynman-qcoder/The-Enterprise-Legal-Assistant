# 11. Layer B nulls preserved, no sentinel leakage
# ---------------------------------------------------------------------------
def test_11_layer_b_nulls_preserved_no_sentinel():
    from chunk_metadata_contract_v1 import (
        PUBLIC_CONTRACT_FORBIDDEN_SUBSTRINGS, CHUNK_ID_HEX_LENGTH,
    )
    forbidden = list(PUBLIC_CONTRACT_FORBIDDEN_SUBSTRINGS)
    bad: list[str] = []
    # chunk_id must be unique *within a strategy output*. Cross-strategy collisions for
    # identical (source_sha, doc_id, chunk_index, bo_start, bo_end) are correct by CMCV1
    # id formula (deterministic on provenance input) and allowed because strategies are
    # never mixed in a single downstream collection within the same environment.
    seen_ids_per_strategy: dict[str, set[str]] = {"A": set(), "B": set()}
    for strat, d in (("A", A_DICT), ("B", B_DICT)):
        seen_ids = seen_ids_per_strategy[strat]
        for rec in d["chunks"]:
            cm = rec["chunk_metadata"]
            # 14. chunk_id unique, length, hex
            cid = cm["chunk_id"]
            if not re.fullmatch(r"[0-9a-f]+", cid or "") or len(cid) != CHUNK_ID_HEX_LENGTH:
                bad.append(f"{strat} invalid chunk_id format/length: {cid!r}")
            if cid in seen_ids:
                bad.append(f"{strat} duplicate chunk_id: {cid!r}")
            seen_ids.add(cid)
            # No sentinel in text + chunk metadata scalar fields
            text = rec.get("text") or ""
            for s in forbidden:
                if s in text:
                    bad.append(f"{strat} {cid} text contains forbidden sentinel {s!r}")
                    break
            for k, v in cm.items():
                if isinstance(v, str):
                    for s in forbidden:
                        if s in v:
                            bad.append(f"{strat} {cid} field {k} contains forbidden sentinel {s!r}")
                            break
            # NULL stays NULL check: CMCV1 Layer B must not contain prohibited "" for optional
            # (if a field should be NULL, keep it None → JSON null, not "").
            # Allow title to be non-empty string for real docs.
            # Fail if any of the nullable scalar fields == "" (fabricated empty string):
            for field_b in (
                "source_org", "publish_date", "creation_date", "effective_date",
                "expiry_date", "document_number", "document_index_number", "document_type",
                "authority_level", "legal_status", "jurisdiction", "region", "theme_category",
                "source_url",
            ):
                v = cm.get(field_b)
                if isinstance(v, str) and v == "":
                    bad.append(f"{strat} {cid} Layer B {field_b} fabricated empty string")
    assert not bad, f"{len(bad)} failures: " + "; ".join(bad[:12])


