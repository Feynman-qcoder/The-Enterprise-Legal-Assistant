def test_15_human_review_package_compliant():
    # a) Case count 20–30
    cases: list[dict[str, str]] = []
    with open(HUMAN_CSV, "r", encoding="utf-8-sig") as f:
        rdr = csv.DictReader(f)
        for row in rdr:
            cases.append(dict(row))
    assert 20 <= len(cases) <= 30, f"review cases={len(cases)}, expected 20-30"
    # b) 用户选择/用户备注 blank
    for c in cases:
        user_choice = c.get("用户选择", "").strip()
        user_note = c.get("用户备注", "").strip()
        assert user_choice == "", f"non-blank 用户选择 in case {c.get('case_id')}: {user_choice!r}"
        assert user_note == "", f"non-blank 用户备注 in case {c.get('case_id')}: {user_note!r}"
    # c) case_id unique, R### prefix
    ids = [c["case_id"] for c in cases]
    assert len(ids) == len(set(ids)), "case_ids not unique"
    for cid in ids:
        assert re.fullmatch(r"R\d{3}_[A-Za-z0-9_]+", cid), f"case_id format wrong {cid!r}"
    # d) fields present
    expected_cols = {"case_id", "document", "context", "Strategy_A", "Strategy_B", "risk_reason", "用户选择", "用户备注"}
    with open(HUMAN_CSV, "r", encoding="utf-8-sig") as f:
        cols = set(csv.reader(f).__next__())
    missing_cols = expected_cols - cols
    assert not missing_cols, f"human review CSV missing cols: {missing_cols}"
    # e) md contains same case_ids referenced
    md_txt = HUMAN_MD.read_text(encoding="utf-8")
    for cid in ids:
        assert cid in md_txt, f"review case {cid} missing from markdown"
    # f) no "winner A / winner B" auto-inserted in 中文文档
    md_txt_lower = md_txt.lower()
    for leak in ("winner", "胜方", "ai 推荐", "ai推荐", "自动判断", "自动选择"):
        assert leak not in md_txt_lower, f"疑似 AI 胜者泄漏关键词: {leak!r}"
