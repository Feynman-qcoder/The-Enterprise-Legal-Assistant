def _cm_from_dict(d: dict):
    import dataclasses as _dc
    from chunk_metadata_contract_v1 import (
        ChunkMetadata, ChunkStructuralContext, ChunkProvenance, ChunkTableContext,
        ChunkParentChildInfo, ChunkQualityFlags,
    )
    d0 = dict(d)
    for field_key, cls in (
        ("structural", ChunkStructuralContext),
        ("provenance", ChunkProvenance),
        ("table_context", ChunkTableContext),
        ("parent_child", ChunkParentChildInfo),
        ("quality", ChunkQualityFlags),
    ):
        if field_key in d0 and isinstance(d0[field_key], dict):
            d0[field_key] = cls(**d0[field_key])
    extras = d0.pop("extras", {})
    valid_keys = {f.name for f in _dc.fields(ChunkMetadata)}
    try:
        cm = ChunkMetadata(**{k: v for k, v in d0.items() if k in valid_keys})
    except TypeError:
        d2 = {k: v for k, v in d0.items() if k in valid_keys}
        cm = ChunkMetadata(**d2)
    if extras:
        cm.extras.update(extras)
    return cm


