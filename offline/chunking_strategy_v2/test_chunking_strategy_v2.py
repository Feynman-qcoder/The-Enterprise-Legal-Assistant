def test_02_03_determinism_a_and_b_on_first_three_loaded_docs():
    # Use pipeline's internal loaded_map (only for docs that were cleanly loaded).
    from _v2_utils import dispatch_parse_and_clean, load_manifest_entries, LoadedDoc
    entries = load_manifest_entries()
    successes = 0
    for entry in entries:
        res = dispatch_parse_and_clean(entry)
        if isinstance(res, tuple):
            continue
        loaded: LoadedDoc = res
        a1, a2, b1, b2 = _run_both(loaded)
        assert len(a1) == len(a2), f"A length mismatch doc={loaded.logical_document_id}: {len(a1)} vs {len(a2)}"
        for i, (c1, c2) in enumerate(zip(a1, a2)):
            assert c1.text == c2.text, f"A text mismatch doc={loaded.logical_document_id} i={i}"
            assert c1._block_orders == c2._block_orders, f"A bo mismatch doc={loaded.logical_document_id} i={i}"
        assert len(b1) == len(b2), f"B length mismatch doc={loaded.logical_document_id}: {len(b1)} vs {len(b2)}"
        for i, (c1, c2) in enumerate(zip(b1, b2)):
            assert c1.text == c2.text, f"B text mismatch doc={loaded.logical_document_id} i={i}"
            assert c1._block_orders == c2._block_orders, f"B bo mismatch doc={loaded.logical_document_id} i={i}"
        successes += 1
        if successes >= 3:
            break
    assert successes >= 1, "No docs loaded successfully to even run determinism on"


