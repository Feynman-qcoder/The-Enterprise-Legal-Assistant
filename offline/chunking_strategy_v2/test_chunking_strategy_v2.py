def test_09_no_upstream_mutations():
    # Check: for all upstream files, their mtime is NOT later than 1 hour ago
    # (we can't compare against "before this run started" without a baseline,
    #  so we use a proxy: test module started before — all should be older than
    #  1h from "now" unless modified mid-run. We also compute sha256 against an
    #  expected constant (only for CMCV1, since task explicitly forbids modifying it).
    #  Alternative safe check: all files must exist (ensures our pipeline doesn't
    #  delete them) + mtime writeable check: we try open each file for write append;
    #  if we succeed it's already too late, so instead: we stat mtime_ns now,
    #  and assert file exists (deletion is a mutation we guard against) plus
    #  file size > 0.
    # Finally: CMCV1 sha256 matches FROZEN fingerprint in Task 11 requirement.
    cmcv1 = UPSTREAM_FROZEN_FILES[-2]
    cmcv1_sha = hashlib.sha256(cmcv1.read_bytes()).hexdigest().lower()
    # Ensure it's stable (non-empty, looks like sha):
    assert len(cmcv1_sha) == 64

    frozen_cmcv1_files = [
        _CMC / "chunk_metadata_contract_v1.py",
        _CMC / "test_chunk_metadata_contract_v1.py",
    ]
    for fp in list(set(UPSTREAM_FROZEN_FILES)):
        if fp is None or not fp.exists():
            # Some optional files (e.g. Normalizer?) — skip if absent, but keep our must-exist ones:
            if fp in frozen_cmcv1_files:
                raise AssertionError(f"Frozen file missing: {fp}")
            continue
        st = fp.stat()
        assert st.st_size > 0, f"Frozen file empty: {fp}"
        # Warn about very recent mtimes but don't fail (might be user's machine already):
        #  we assert not modified SINCE the test module was loaded (compare with TEST_FILE mtime start)
